export type DictKey = keyof (typeof dict)["ru"];

export function tr(lang: Lang, key: DictKey): string {
  return dict[lang][key] ?? dict.ru[key] ?? key;
}

/** Локализованная подпись из TD: {ru, en} | строка */
export function labelOf(
  label: Record<string, string> | string | undefined,
  lang: Lang,
  fallback = ""
): string {
  if (!label) return fallback;
  if (typeof label === "string") return label;
  return label[lang] ?? label.ru ?? label.en ?? Object.values(label)[0] ?? fallback;
}
